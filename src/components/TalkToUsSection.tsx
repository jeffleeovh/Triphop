import React, { useState, useEffect } from 'react';
import { MessageSquare, Users, Sparkles, ShieldCheck, Key, Send, ThumbsUp, MessageCircle, ExternalLink, RefreshCw, CheckCircle2 } from 'lucide-react';
import { DiscussionEmbed, CommentCount } from 'disqus-react';
import { DisqusErrorBoundary } from './DisqusErrorBoundary.tsx';

interface CommunityComment {
  id: string;
  author: string;
  role: string;
  topic: string;
  content: string;
  timestamp: string;
  likes: number;
}

export const TalkToUsSection: React.FC = () => {
  const [activeTopic, setActiveTopic] = useState<'general' | 'teambuilding' | 'weather'>('general');
  const [enableSSO, setEnableSSO] = useState<boolean>(false);
  const [authorName, setAuthorName] = useState<string>('');
  const [authorRole, setAuthorRole] = useState<string>('Corporate Planner');
  const [newComment, setNewComment] = useState<string>('');
  const [submitted, setSubmitted] = useState<boolean>(false);

  // Initial community comments
  const [comments, setComments] = useState<CommunityComment[]>([
    {
      id: 'c1',
      author: 'Marcus Wee',
      role: 'Corporate HR Lead',
      topic: 'teambuilding',
      content: 'We used Trip Hop to coordinate an outing of 18 colleagues for iFly Sentosa and dragon boating at Kallang. The HR tax invoice breakdown with 9% GST made expense approvals effortless!',
      timestamp: '2 hours ago',
      likes: 14,
    },
    {
      id: 'c2',
      author: 'Elena & Daniel',
      role: 'Couple Travelers',
      topic: 'general',
      content: 'Loved the Lau Pa Sat Satay Street recommendation after walking Gardens by the Bay! The transparent per-pax pricing helped us budget Singapore without any surprises.',
      timestamp: 'Yesterday',
      likes: 8,
    },
    {
      id: 'c3',
      author: 'Priya Raman',
      role: 'Family of 5',
      topic: 'weather',
      content: 'When the 2-hour forecast flashed rain alerts in Marina Bay, the automatic switch to the Cloud Forest sheltered itinerary saved our day with the kids. Truly rain-proof!',
      timestamp: '2 days ago',
      likes: 19,
    },
  ]);

  const topics = {
    general: {
      id: 'triphop-community-forum',
      title: 'Trip Hop Singapore Community Forum & Outing Discussions',
      description: 'Discuss Singapore excursions, recommend weekend spots, and share travel feedback with other planners.',
    },
    teambuilding: {
      id: 'triphop-teambuilding-discussions',
      title: 'Corporate Team Building & Bonding Activities',
      description: 'Exchange team retreat ideas, pricing questions, and corporate outing experiences.',
    },
    weather: {
      id: 'triphop-rain-contingencies',
      title: 'Wet Weather & Sheltered Singapore Itineraries',
      description: 'Share your top rainy-day sheltered suggestions across Singapore.',
    },
  };

  const currentTopic = topics[activeTopic];
  const currentOrigin = typeof window !== 'undefined' ? window.location.origin : 'https://triphop-singapore.app';
  const article = {
    url: `${currentOrigin}/talk-to-us#${currentTopic.id}`,
    id: currentTopic.id,
    title: currentTopic.title,
  };

  const disqusShortname = 'vibe-coding-5';

  // 1. Standard Discussion Embed Config matching user specification
  const standardConfig = {
    url: article.url,
    identifier: article.id,
    title: article.title,
    language: 'en',
  };

  // 3. SSO Discussion Embed Config matching user specification
  const ssoConfig = {
    url: article.url,
    identifier: article.id,
    title: article.title,
    language: 'EN',
    remoteAuthS3: '', // Generated by your server
    apiKey: '', // Your API key
    sso: {
      name: 'SampleNews',
      button: 'http://example.com/images/samplenews.gif',
      icon: 'http://example.com/favicon.png',
      url: `${currentOrigin}/login/`,
      logout: `${currentOrigin}/logout/`,
      profile_url: `${currentOrigin}/profile/{username}`,
      width: '800',
      height: '400',
    },
  };

  const activeConfig = enableSSO ? ssoConfig : standardConfig;

  const handlePostComment = (e: React.FormEvent) => {
    e.preventDefault();
    if (!newComment.trim()) return;

    const item: CommunityComment = {
      id: `c-${Date.now()}`,
      author: authorName.trim() || 'Singapore Explorer',
      role: authorRole,
      topic: activeTopic,
      content: newComment.trim(),
      timestamp: 'Just now',
      likes: 1,
    };

    setComments([item, ...comments]);
    setNewComment('');
    setSubmitted(true);
    setTimeout(() => setSubmitted(false), 3000);
  };

  const handleLike = (id: string) => {
    setComments(
      comments.map((c) => (c.id === id ? { ...c, likes: c.likes + 1 } : c))
    );
  };

  const filteredComments = comments.filter(
    (c) => activeTopic === 'general' || c.topic === activeTopic
  );

  return (
    <div className="space-y-8 animate-fadeIn">
      {/* Header Banner */}
      <div className="p-6 sm:p-8 rounded-3xl bg-gradient-to-r from-teal-50 via-emerald-50 to-cyan-50 border-2 border-emerald-200 shadow-sm">
        <div className="flex flex-col md:flex-row md:items-center justify-between gap-5">
          <div className="flex items-start gap-4">
            <div className="w-12 h-12 rounded-2xl bg-gradient-to-tr from-emerald-500 to-teal-500 text-white flex items-center justify-center shadow-md shadow-emerald-500/25 flex-shrink-0">
              <MessageSquare className="w-6 h-6" />
            </div>
            <div>
              <div className="flex items-center gap-2.5 flex-wrap">
                <h2 className="font-display font-extrabold text-2xl text-slate-900">
                  Talk to Us &amp; Community Forum
                </h2>
                <span className="text-xs font-mono font-bold px-2.5 py-0.5 rounded-full bg-white text-emerald-800 border border-emerald-300 shadow-xs">
                  Disqus: {disqusShortname}
                </span>

                {/* 2. Comment Count Component */}
                <span className="text-xs font-bold px-2.5 py-0.5 rounded-full bg-emerald-100 text-emerald-900 border border-emerald-300">
                  <DisqusErrorBoundary>
                    <CommentCount
                      shortname={disqusShortname}
                      config={{
                        url: article.url,
                        identifier: article.id,
                        title: article.title,
                      }}
                    >
                      Comments ({comments.length})
                    </CommentCount>
                  </DisqusErrorBoundary>
                </span>
              </div>
              <p className="text-sm text-slate-600 mt-1 max-w-2xl font-medium">
                Connect with Singapore excursion planners, share itinerary reviews, ask corporate team building questions, or chat with the team.
              </p>
            </div>
          </div>

          {/* Forum SSO Configuration Mode */}
          <div className="flex items-center gap-2 self-start md:self-auto bg-white p-2 rounded-2xl border-2 border-slate-200 shadow-xs">
            <button
              onClick={() => setEnableSSO(false)}
              className={`px-3 py-1.5 rounded-xl text-xs font-bold transition-all ${
                !enableSSO
                  ? 'bg-emerald-600 text-white shadow-xs'
                  : 'text-slate-600 hover:text-slate-900'
              }`}
            >
              Standard Embed
            </button>
            <button
              onClick={() => setEnableSSO(true)}
              className={`flex items-center gap-1 px-3 py-1.5 rounded-xl text-xs font-bold transition-all ${
                enableSSO
                  ? 'bg-emerald-600 text-white shadow-xs'
                  : 'text-slate-600 hover:text-slate-900'
              }`}
            >
              <Key className="w-3.5 h-3.5" />
              <span>SSO Config</span>
            </button>
          </div>
        </div>
      </div>

      {/* Discussion Category Filter Pills */}
      <div className="flex items-center gap-2 overflow-x-auto pb-1">
        <button
          onClick={() => setActiveTopic('general')}
          className={`flex items-center gap-1.5 px-4 py-2.5 rounded-2xl text-xs sm:text-sm font-extrabold transition-all border-2 ${
            activeTopic === 'general'
              ? 'bg-emerald-600 text-white border-emerald-600 shadow-sm'
              : 'bg-white text-slate-700 border-slate-200 hover:border-slate-300 hover:text-slate-900'
          }`}
        >
          <Sparkles className="w-4 h-4" />
          <span>General Community &amp; Tips</span>
        </button>

        <button
          onClick={() => setActiveTopic('teambuilding')}
          className={`flex items-center gap-1.5 px-4 py-2.5 rounded-2xl text-xs sm:text-sm font-extrabold transition-all border-2 ${
            activeTopic === 'teambuilding'
              ? 'bg-emerald-600 text-white border-emerald-600 shadow-sm'
              : 'bg-white text-slate-700 border-slate-200 hover:border-slate-300 hover:text-slate-900'
          }`}
        >
          <Users className="w-4 h-4" />
          <span>Corporate Team Building</span>
        </button>

        <button
          onClick={() => setActiveTopic('weather')}
          className={`flex items-center gap-1.5 px-4 py-2.5 rounded-2xl text-xs sm:text-sm font-extrabold transition-all border-2 ${
            activeTopic === 'weather'
              ? 'bg-emerald-600 text-white border-emerald-600 shadow-sm'
              : 'bg-white text-slate-700 border-slate-200 hover:border-slate-300 hover:text-slate-900'
          }`}
        >
          <ShieldCheck className="w-4 h-4" />
          <span>Rain &amp; Sheltered Backup Plans</span>
        </button>
      </div>

      {/* Interactive Quick Post Form */}
      <div className="p-6 sm:p-8 rounded-3xl bg-white border-2 border-slate-200 shadow-md">
        <div className="flex items-center justify-between pb-4 mb-4 border-b-2 border-slate-100">
          <div>
            <h3 className="font-display font-extrabold text-lg text-slate-900">
              Post to "{currentTopic.title}"
            </h3>
            <p className="text-xs text-slate-500 mt-0.5">
              Live instant community discussion board for Singapore explorers
            </p>
          </div>
          <span className="text-xs font-mono font-bold text-emerald-700 bg-emerald-50 px-3 py-1 rounded-xl border border-emerald-200">
            Thread #{article.id}
          </span>
        </div>

        <form onSubmit={handlePostComment} className="space-y-4">
          <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
            <div>
              <label className="block text-xs font-bold text-slate-700 mb-1">Your Name</label>
              <input
                type="text"
                placeholder="e.g. Rachel Koh"
                value={authorName}
                onChange={(e) => setAuthorName(e.target.value)}
                className="w-full bg-slate-50 border-2 border-slate-200 rounded-xl px-3.5 py-2 text-sm text-slate-900 focus:outline-none focus:border-emerald-500 focus:bg-white"
              />
            </div>
            <div>
              <label className="block text-xs font-bold text-slate-700 mb-1">Traveler Type / Organization</label>
              <select
                value={authorRole}
                onChange={(e) => setAuthorRole(e.target.value)}
                className="w-full bg-slate-50 border-2 border-slate-200 rounded-xl px-3.5 py-2 text-sm text-slate-900 focus:outline-none focus:border-emerald-500 focus:bg-white"
              >
                <option value="Corporate Planner">Corporate Planner / HR</option>
                <option value="Family Traveler">Family (3+ Pax)</option>
                <option value="Couple Traveler">Couple / Duo</option>
                <option value="Friend Group">Friend Group</option>
                <option value="Singapore Local">Singapore Local</option>
              </select>
            </div>
          </div>

          <div>
            <label className="block text-xs font-bold text-slate-700 mb-1">Your Review, Question or Suggestion</label>
            <textarea
              rows={3}
              placeholder="Share advice, feedback on attractions, or ask for Singapore outing tips..."
              value={newComment}
              onChange={(e) => setNewComment(e.target.value)}
              className="w-full bg-slate-50 border-2 border-slate-200 rounded-xl p-3 text-sm text-slate-900 focus:outline-none focus:border-emerald-500 focus:bg-white"
            />
          </div>

          <div className="flex items-center justify-between gap-3 pt-2">
            {submitted ? (
              <span className="flex items-center gap-1.5 text-xs font-bold text-emerald-700 animate-fadeIn">
                <CheckCircle2 className="w-4 h-4 text-emerald-600" />
                Comment posted successfully!
              </span>
            ) : (
              <span className="text-xs text-slate-500">
                Visible instantly to community members
              </span>
            )}

            <button
              type="submit"
              className="flex items-center gap-2 px-5 py-2.5 rounded-xl font-extrabold text-sm bg-gradient-to-r from-emerald-600 to-teal-600 hover:from-emerald-700 hover:to-teal-700 text-white shadow-md shadow-emerald-600/20 transition-all active:scale-95"
            >
              <Send className="w-4 h-4" />
              <span>Post Message</span>
            </button>
          </div>
        </form>
      </div>

      {/* Community Message Feed */}
      <div className="space-y-4">
        <div className="flex items-center justify-between">
          <h3 className="font-display font-extrabold text-lg text-slate-900 flex items-center gap-2">
            <MessageCircle className="w-5 h-5 text-emerald-600" />
            <span>Community Feedback &amp; Experiences ({filteredComments.length})</span>
          </h3>
          <span className="text-xs text-slate-500 font-mono">Live Sync</span>
        </div>

        <div className="grid grid-cols-1 md:grid-cols-3 gap-4">
          {filteredComments.map((item) => (
            <div
              key={item.id}
              className="p-5 rounded-3xl bg-white border-2 border-slate-200 hover:border-emerald-400 transition-all shadow-sm flex flex-col justify-between"
            >
              <div>
                <div className="flex items-center justify-between mb-2">
                  <span className="text-xs font-mono font-bold px-2 py-0.5 rounded-lg bg-emerald-50 text-emerald-800 border border-emerald-200">
                    {item.role}
                  </span>
                  <span className="text-[11px] text-slate-400 font-medium">{item.timestamp}</span>
                </div>
                <h4 className="font-display font-extrabold text-sm text-slate-900 mb-2">
                  {item.author}
                </h4>
                <p className="text-xs text-slate-600 leading-relaxed font-normal">
                  "{item.content}"
                </p>
              </div>

              <div className="pt-3 mt-4 border-t border-slate-100 flex items-center justify-between">
                <button
                  onClick={() => handleLike(item.id)}
                  className="flex items-center gap-1.5 text-xs font-bold text-slate-500 hover:text-emerald-700 transition-colors"
                >
                  <ThumbsUp className="w-3.5 h-3.5" />
                  <span>Helpful ({item.likes})</span>
                </button>
                <span className="text-[11px] font-mono text-slate-400">Singapore Outing</span>
              </div>
            </div>
          ))}
        </div>
      </div>

      {/* 1 & 3. Disqus Thread Section as requested */}
      <div className="p-6 sm:p-8 rounded-3xl bg-white border-2 border-slate-200 shadow-xl space-y-4">
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 pb-4 border-b-2 border-slate-100">
          <div>
            <div className="flex items-center gap-2">
              <span className="text-xs font-mono font-extrabold uppercase tracking-wider text-emerald-700">
                Disqus Embedded Widget
              </span>
              <span className="px-2.5 py-0.5 rounded-full text-xs font-bold bg-slate-100 text-slate-700 border border-slate-200">
                Forum: {disqusShortname}
              </span>
            </div>
            <h3 className="font-display font-extrabold text-lg text-slate-900 mt-1">
              Disqus Discussion Stream
            </h3>
          </div>

          <a
            href={`https://${disqusShortname}.disqus.com`}
            target="_blank"
            rel="noopener noreferrer"
            className="flex items-center gap-1.5 px-4 py-2 rounded-xl text-xs font-extrabold bg-slate-100 hover:bg-slate-200 text-slate-800 border border-slate-200 transition-all self-start sm:self-auto"
          >
            <span>Open on Disqus Portal</span>
            <ExternalLink className="w-3.5 h-3.5" />
          </a>
        </div>

        {/* Embedded Disqus Component */}
        <div className="min-h-[300px]">
          <DisqusErrorBoundary>
            <DiscussionEmbed
              key={`${article.id}-${enableSSO ? 'sso' : 'std'}`}
              shortname={disqusShortname}
              config={activeConfig}
            />
          </DisqusErrorBoundary>
        </div>
      </div>
    </div>
  );
};

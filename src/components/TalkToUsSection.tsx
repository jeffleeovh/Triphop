import React, { useState } from 'react';
import { MessageSquare, Users, Sparkles, ShieldCheck, Key, Shield, ExternalLink, RefreshCw } from 'lucide-react';
import { DiscussionEmbed, CommentCount } from 'disqus-react';
import { DisqusErrorBoundary } from './DisqusErrorBoundary.tsx';

interface ArticleProps {
  url: string;
  id: string;
  title: string;
}

interface TalkToUsSectionProps {
  article?: ArticleProps;
}

export const TalkToUsSection: React.FC<TalkToUsSectionProps> = ({ article: propArticle }) => {
  const [activeTopic, setActiveTopic] = useState<'general' | 'teambuilding' | 'weather'>('general');
  const [enableSSO, setEnableSSO] = useState<boolean>(false);

  const topics = {
    general: {
      id: 'triphop-community-forum',
      title: 'Trip Hop Singapore Community Forum & Outing Discussions',
      description: 'Discuss Singapore excursions, recommend weekend spots, and share travel feedback with other planners.',
    },
    teambuilding: {
      id: 'triphop-teambuilding-discussions',
      title: 'Corporate Team Building & Bonding Activities',
      description: 'Exchange team retreat ideas, pricing questions, and corporate outing experiences.',
    },
    weather: {
      id: 'triphop-rain-contingencies',
      title: 'Wet Weather & Sheltered Singapore Itineraries',
      description: 'Share your top rainy-day sheltered suggestions across Singapore.',
    },
  };

  const currentTopic = topics[activeTopic];

  // Article representation matching user request: url, id, title
  const currentOrigin = typeof window !== 'undefined' ? window.location.origin : 'https://triphop-singapore.app';
  const article: ArticleProps = propArticle || {
    url: `${currentOrigin}/talk-to-us#${currentTopic.id}`,
    id: currentTopic.id,
    title: currentTopic.title,
  };

  const disqusShortname = 'vibe-coding-5';

  // 1. Standard Discussion Embed Config
  const standardConfig = {
    url: article.url,
    identifier: article.id,
    title: article.title,
    language: 'en',
  };

  // 3. SSO Discussion Embed Config (as specified in request)
  const ssoConfig = {
    url: article.url,
    identifier: article.id,
    title: article.title,
    language: 'EN',
    remoteAuthS3: '', // Generated by your server (see https://help.disqus.com/customer/en/articles/1717160-integrating-single-sign-on for more details)
    apiKey: '', // Your API key that can be generated or referenced at https://disqus.com/api/applications/
    sso: {
      name: 'TripHopCommunity',
      button: 'https://images.unsplash.com/photo-1517245386807-bb43f82c33c4?w=100&auto=format&fit=crop',
      icon: 'https://images.unsplash.com/photo-1517245386807-bb43f82c33c4?w=64&auto=format&fit=crop',
      url: `${currentOrigin}/login/`,
      logout: `${currentOrigin}/logout/`,
      profile_url: `${currentOrigin}/profile/{username}`,
      width: '800',
      height: '400',
    },
  };

  const activeConfig = enableSSO ? ssoConfig : standardConfig;

  return (
    <div className="space-y-6">
      {/* Header Banner */}
      <div className="p-6 sm:p-8 rounded-3xl bg-gradient-to-r from-teal-50 via-emerald-50 to-cyan-50 border-2 border-emerald-200 shadow-sm">
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
          <div className="flex items-start gap-4">
            <div className="w-12 h-12 rounded-2xl bg-gradient-to-tr from-emerald-500 to-teal-500 text-white flex items-center justify-center shadow-md shadow-emerald-500/25 flex-shrink-0">
              <MessageSquare className="w-6 h-6" />
            </div>
            <div>
              <div className="flex items-center gap-2.5 flex-wrap">
                <h2 className="font-display font-extrabold text-2xl text-slate-900">
                  Talk to Us &amp; Discussion Forum
                </h2>
                <span className="text-xs font-mono font-bold px-2.5 py-0.5 rounded-full bg-white text-emerald-800 border border-emerald-300 shadow-xs">
                  Disqus: {disqusShortname}
                </span>

                {/* 2. Comment Count Component as requested */}
                <span className="text-xs font-bold px-2.5 py-0.5 rounded-full bg-emerald-100 text-emerald-900 border border-emerald-300">
                  <DisqusErrorBoundary>
                    <CommentCount
                      shortname={disqusShortname}
                      config={{
                        url: article.url,
                        identifier: article.id,
                        title: article.title,
                      }}
                    >
                      {/* Placeholder Text */}
                      Comments
                    </CommentCount>
                  </DisqusErrorBoundary>
                </span>
              </div>
              <p className="text-sm text-slate-600 mt-1 max-w-2xl">
                Connect with Singapore excursion planners, leave ideas for itineraries, or ask corporate team building questions.
              </p>
            </div>
          </div>

          {/* SSO Configuration Toggle */}
          <div className="flex items-center gap-2 self-start sm:self-auto bg-white p-2 rounded-2xl border-2 border-slate-200 shadow-xs">
            <button
              onClick={() => setEnableSSO(false)}
              className={`px-3 py-1.5 rounded-xl text-xs font-bold transition-all ${
                !enableSSO
                  ? 'bg-emerald-600 text-white shadow-xs'
                  : 'text-slate-600 hover:text-slate-900'
              }`}
            >
              Standard Forum
            </button>
            <button
              onClick={() => setEnableSSO(true)}
              className={`flex items-center gap-1 px-3 py-1.5 rounded-xl text-xs font-bold transition-all ${
                enableSSO
                  ? 'bg-emerald-600 text-white shadow-xs'
                  : 'text-slate-600 hover:text-slate-900'
              }`}
            >
              <Key className="w-3.5 h-3.5" />
              <span>SSO Enabled</span>
            </button>
          </div>
        </div>
      </div>

      {/* Discussion Category Selector */}
      <div className="flex items-center gap-2 overflow-x-auto pb-1">
        <button
          onClick={() => setActiveTopic('general')}
          className={`flex items-center gap-1.5 px-4 py-2.5 rounded-2xl text-xs sm:text-sm font-extrabold transition-all border-2 ${
            activeTopic === 'general'
              ? 'bg-emerald-600 text-white border-emerald-600 shadow-sm'
              : 'bg-white text-slate-700 border-slate-200 hover:border-slate-300 hover:text-slate-900'
          }`}
        >
          <Sparkles className="w-4 h-4" />
          <span>General Community</span>
        </button>

        <button
          onClick={() => setActiveTopic('teambuilding')}
          className={`flex items-center gap-1.5 px-4 py-2.5 rounded-2xl text-xs sm:text-sm font-extrabold transition-all border-2 ${
            activeTopic === 'teambuilding'
              ? 'bg-emerald-600 text-white border-emerald-600 shadow-sm'
              : 'bg-white text-slate-700 border-slate-200 hover:border-slate-300 hover:text-slate-900'
          }`}
        >
          <Users className="w-4 h-4" />
          <span>Corporate Team Building</span>
        </button>

        <button
          onClick={() => setActiveTopic('weather')}
          className={`flex items-center gap-1.5 px-4 py-2.5 rounded-2xl text-xs sm:text-sm font-extrabold transition-all border-2 ${
            activeTopic === 'weather'
              ? 'bg-emerald-600 text-white border-emerald-600 shadow-sm'
              : 'bg-white text-slate-700 border-slate-200 hover:border-slate-300 hover:text-slate-900'
          }`}
        >
          <ShieldCheck className="w-4 h-4" />
          <span>Rain &amp; Sheltered Contingencies</span>
        </button>
      </div>

      {/* Active Thread Meta Card */}
      <div className="p-5 rounded-2xl bg-white border-2 border-slate-200 shadow-xs flex flex-col sm:flex-row sm:items-center justify-between gap-3">
        <div>
          <span className="text-xs font-mono font-bold text-slate-500 uppercase">
            Active Thread: {article.id}
          </span>
          <h3 className="font-display font-extrabold text-base text-slate-900 mt-0.5">
            {article.title}
          </h3>
          <p className="text-xs text-slate-600 mt-0.5">
            {currentTopic.description}
          </p>
        </div>

        {enableSSO && (
          <div className="p-2.5 rounded-xl bg-teal-50 border border-teal-200 text-xs text-teal-900 font-mono">
            <span className="font-bold flex items-center gap-1">
              <Shield className="w-3.5 h-3.5 text-teal-600" />
              SSO Configuration Active (remoteAuthS3 ready)
            </span>
          </div>
        )}
      </div>

      {/* 1 & 3. Discussion Embed Component as requested */}
      <div className="p-6 sm:p-8 rounded-3xl bg-white border-2 border-slate-200 shadow-xl min-h-[420px]">
        <DisqusErrorBoundary>
          <DiscussionEmbed
            key={`${article.id}-${enableSSO ? 'sso' : 'std'}`}
            shortname={disqusShortname}
            config={activeConfig}
          />
        </DisqusErrorBoundary>
      </div>
    </div>
  );
};
